#!/usr/bin/env python3
"""Development-only original Camera projection arithmetic reference.

The unchanged original projection getter, matrix constructor/copy, and ARMv6
libgcc execute. Only platform tanf, memcpy and unwind bookkeeping have host
boundaries. Replay both faithfully rounded tanf results at each captured
argument, separately from the historical host-libm run. No camera placement,
GPU frame or historical libm identity claim.
"""
import argparse
import ctypes
import ctypes.util
from fractions import Fraction
import hashlib
import json
from pathlib import Path
import struct
import sys


def bits(value):return struct.unpack('<I',struct.pack('<f',value))[0]
def value(raw):return struct.unpack('<f',struct.pack('<I',raw))[0]
def sha(data):return hashlib.sha256(data).hexdigest()


def tangent_bracket(input_bits):
    """Prove the two adjacent binary32 bounds without using any host libm.

    These fixture arguments are in (0, 1.5). Exact rational alternating
    sine/cosine series bound the remainder by the next term. Division of
    positive interval endpoints encloses the exact tangent. No approximate
    arithmetic determines whether the final adjacent floats enclose it.
    """
    x=Fraction(value(input_bits))
    if not 0<x<Fraction(3,2):raise ValueError('tangent proof fixture domain exceeded')
    def series(cosine):
        term=Fraction(1) if cosine else x
        total=term
        for n in range(1,256):
            denominator=(2*n-1)*(2*n) if cosine else (2*n)*(2*n+1)
            term=-term*x*x/denominator
            if abs(term)<Fraction(1,1<<256):
                return min(total,total+term),max(total,total+term),n
            total+=term
        raise RuntimeError('tangent proof failed to converge')
    sin_lo,sin_hi,sin_terms=series(False)
    cos_lo,cos_hi,cos_terms=series(True)
    if not sin_lo>0 or not cos_lo>0:raise RuntimeError('nonpositive proof interval')
    lo,hi=sin_lo/cos_hi,sin_hi/cos_lo
    # Binary64 supplies only a search seed; all decisions below use exact
    # rationals and also reject an interval that crosses a binary32 value.
    lower=bits(float((lo+hi)/2))
    while Fraction(value(lower))>lo:lower-=1
    while Fraction(value(lower+1))<=lo:lower+=1
    if not Fraction(value(lower))<lo<hi<Fraction(value(lower+1)):
        raise RuntimeError('tangent interval does not prove adjacent float bounds')
    if not hi-lo<Fraction(1,1<<240):raise RuntimeError('tangent enclosure too wide')
    return {'lower_bits':lower,'upper_bits':lower+1,
            'series_terms':[sin_terms,cos_terms],'enclosure_width_less_than_2_pow_minus_240':True}


def header(record):
    lines=['// Generated by camera_oracle.py from unchanged-original synthetic cases.',
        '#pragma once','#include <array>','#include <cstddef>','#include <cstdint>',
        'namespace g1_camera_fixture {',
        'struct Case { std::uint8_t type; std::array<float,4> parameters; std::array<std::uint32_t,16> matrix_bits; };',
        'inline constexpr std::array<Case,%d> cases{{' % len(record['cases'])]
    for row in record['cases']:
        params=','.join(float(v).hex()+'F' for v in row['parameters'])
        matrix=','.join('0x%08xU'%v for v in row['matrix_bits'])
        lines.append('    {%d,{{%s}},{{%s}}},'%(row['type'],params,matrix))
    lines.extend(['}};',
        '// Captured original argument, historical host result, and exact-original',
        '// matrix replays for the two floats bracketing the mathematical tangent.',
        'struct TangentBoundary { std::size_t case_index; std::uint32_t input_bits, historical_output_bits, lower_bits, upper_bits; std::array<std::uint32_t,16> lower_matrix_bits, upper_matrix_bits; };',
        'inline constexpr std::array<TangentBoundary,%d> tangent_boundaries{{' % len(record['tangent_boundaries'])])
    for row in record['tangent_boundaries']:
        lower=','.join('0x%08xU'%v for v in row['lower_matrix_bits'])
        upper=','.join('0x%08xU'%v for v in row['upper_matrix_bits'])
        lines.append('    {%d,0x%08xU,0x%08xU,0x%08xU,0x%08xU,{{%s}},{{%s}}},'%(
            row['case_index'],row['input_bits'],row['historical_output_bits'],
            row['lower_bits'],row['upper_bits'],lower,upper))
    lines.extend(['}};','} // namespace g1_camera_fixture',''])
    return '\n'.join(lines)


def main():
    ap=argparse.ArgumentParser(description=__doc__)
    for name in ('binary','libgcc','unicorn-dir','output'):
        ap.add_argument('--'+name,type=Path,required=True)
    ap.add_argument('--fixture-header',type=Path)
    args=ap.parse_args();sys.path.insert(0,str(args.unicorn_dir))
    sys.path.insert(0,str(Path(__file__).resolve().parent.parent/'sprite'))
    import render_oracle as base
    import unicorn
    image,gcc=args.binary.read_bytes(),args.libgcc.read_bytes()
    if sha(image)!=base.IMAGE_SHA or sha(gcc)!=base.LIBGCC_SHA:raise ValueError('private original input hash mismatch')
    base.MATH.update({0xba228:'___addsf3vfp',0xba3b4:'___subsf3vfp'})

    class OriginalCamera(base.OriginalRenderer):
        def __init__(self):
            super().__init__(image,gcc)
            self.libm=ctypes.CDLL(ctypes.util.find_library('m'))
            self.libm.tanf.argtypes=[ctypes.c_float];self.libm.tanf.restype=ctypes.c_float
            self.tanf_calls=[]
            self.tanf_replay=None
            # Audited non-lazy symbol-pointer bindings, not instruction edits.
            self.word(0xd2304,0x99979) # CssMatrix::C1(float x16)
            self.word(0xd2308,0x99939) # CssMatrix::C2(float x16)
        def hook(self,instance,address,size,user):
            ar=self.ar
            if address==0xbabf4:
                source=instance.reg_read(ar.UC_ARM_REG_R0)
                if self.tanf_replay is None:
                    result=bits(self.libm.tanf(value(source)))
                else:
                    expected,result=self.tanf_replay
                    if source!=expected:raise RuntimeError('original tangent replay argument changed')
                self.tanf_calls.append({'input_bits':source,'output_bits':result})
                instance.reg_write(ar.UC_ARM_REG_R0,result)
                instance.reg_write(ar.UC_ARM_REG_PC,instance.reg_read(ar.UC_ARM_REG_LR));return
            if address==0xbaa44:
                dst,src,count=[instance.reg_read(r) for r in (ar.UC_ARM_REG_R0,ar.UC_ARM_REG_R1,ar.UC_ARM_REG_R2)]
                if count>4096:raise RuntimeError('unexpected camera memcpy size')
                instance.mem_write(dst,bytes(instance.mem_read(src,count)))
                instance.reg_write(ar.UC_ARM_REG_PC,instance.reg_read(ar.UC_ARM_REG_LR));return
            if address==0xb1bc6:raise RuntimeError('original camera rejected seeded state')
            if 0xba000<=address<0xbb000 and address not in self.math and address not in (0xba1f8,0xba210,0xba204):
                raise RuntimeError('unexpected external camera boundary '+hex(address))
            super().hook(instance,address,size,user)
        def run(self,projection,parameters):
            camera=self.alloc(0x100)
            self.word(camera+0x9c,projection);self.u.mem_write(camera+0xa0,b'\x01')
            fovy,aspect,near,far=parameters
            for offset,v in ((0xe8,fovy),(0xec,fovy),(0xf0,aspect),(0xf4,near),(0xf8,far)):
                self.word(camera+offset,bits(v))
            self.call(0x8c4b4,[camera])
            if self.u.reg_read(self.ar.UC_ARM_REG_R0)!=camera+0xa4:raise RuntimeError('unexpected original matrix pointer')
            return list(struct.unpack('<16I',self.u.mem_read(camera+0xa4,64)))

    original=OriginalCamera()
    inputs=[(50,[30,1.5,2,5000]),(50,[60,1,1,100]),(50,[90,2,0.25,16]),
            (50,[1,0.5,1,10000]),(50,[120,2.5,50,2]),(50,[45,1.3333333730697632,0.1,1000]),
            (49,[10,1.5,2,5000]),(49,[1,1,-10,10]),(49,[128,2,50,-50]),
            (49,[0.25,0.5,1,2]),(49,[100,2.5,0,1000]),(49,[3,1.3333333730697632,-2,-1])]
    cases=[]
    for projection,parameters in inputs:
        parameters=[value(bits(v)) for v in parameters]
        cases.append({'type':projection,'parameters':parameters,'matrix_bits':original.run(projection,parameters)})
    historical_tanf_calls=list(original.tanf_calls)
    tangent_boundaries=[]
    perspective_cases=[(index,row) for index,row in enumerate(cases) if row['type']==50]
    if len(historical_tanf_calls)!=len(perspective_cases):raise RuntimeError('unexpected tangent call count')
    for (index,row),call in zip(perspective_cases,historical_tanf_calls):
        boundary={'case_index':index,'input_bits':call['input_bits'],
                  'historical_output_bits':call['output_bits'],**tangent_bracket(call['input_bits'])}
        for side in ('lower','upper'):
            original.tanf_replay=(call['input_bits'],boundary[side+'_bits'])
            before=len(original.tanf_calls)
            boundary[side+'_matrix_bits']=original.run(row['type'],row['parameters'])
            if len(original.tanf_calls)!=before+1:raise RuntimeError('unexpected replay tangent count')
            if call['output_bits']==boundary[side+'_bits'] and row['matrix_bits']!=boundary[side+'_matrix_bits']:
                raise RuntimeError('historical host-boundary matrix changed during replay')
        original.tanf_replay=None
        tangent_boundaries.append(boundary)
    report={'schema':2,'kind':'unchanged original Camera projection arithmetic with explicit tanf replays',
        'original_image_sha256':base.IMAGE_SHA,'original_libgcc_sha256':base.LIBGCC_SHA,
        'unicorn_version':unicorn.__version__,'runner_sha256':sha(Path(__file__).read_bytes()),
        'loader_sha256':sha(Path(base.__file__).read_bytes()),
        'functions':['0x8c4b4','0x8c2c2','0x99978','0x99938','0x94d22'],
        'data_bindings':{'0xd2304':'original CssMatrix::C1 at0x99979','0xd2308':'original CssMatrix::C2 at0x99939'},
        'boundaries':['host libm tanf with binary32 argument/result; separate exact captured-argument/result replays',
                      'external memcpy','nonthrowing unwind registration/unregistration'],
        'historical_ios_libm_bit_identity':False,'instruction_patches':0,
        'original_text_readonly_unchanged':True,'original_libgcc_readonly_unchanged':True,
        'cases':cases,'tanf_calls':historical_tanf_calls,'tangent_boundaries':tangent_boundaries,
        'replay_tanf_calls':original.tanf_calls[len(historical_tanf_calls):],
        'tangent_bracket_method':'exact rational alternating sine/cosine enclosures; next terms < 2^-256; positive interval division; adjacent binary32 endpoints checked exactly',
        'gpu_execution':False}
    args.output.parent.mkdir(parents=True,exist_ok=True);args.output.write_text(json.dumps(report,indent=2)+'\n')
    if args.fixture_header:args.fixture_header.write_text(header(report))
    print(json.dumps({'cases':len(cases),'historical_matrix_scalars':len(cases)*16,
                      'boundary_replays':len(tangent_boundaries)*2,
                      'replay_matrix_scalars':len(tangent_boundaries)*32,'output':str(args.output)}))


if __name__=='__main__':main()
