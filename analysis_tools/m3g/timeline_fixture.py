#!/usr/bin/env python3
"""Convert the development-only original timeline record to a C++ test fixture.

This reads only the synthetic result JSON, not the original executable, and
does not execute a CPU emulator. The resulting header belongs to tests only.
"""
import argparse
import hashlib
import json
from pathlib import Path
import struct


def generate(path):
    data=path.read_bytes()
    record=json.loads(data)
    cases=record["cases"]
    if record["case_count"]!=len(cases) or len(cases)!=54:
        raise ValueError("expected the audited 54 original timeline cases")
    if record["instruction_patches"]!=0 or not record["original_text_readonly_unchanged"] or not record["original_libgcc_readonly_unchanged"]:
        raise ValueError("reference lacks unchanged-instruction evidence")
    lines=["// Generated by analysis_tools/m3g/timeline_fixture.py; test data only.",
           "#pragma once","#include <array>","#include <cstdint>",
           "namespace g1_timeline_fixture {",
           'inline constexpr char source_sha256[]="'+hashlib.sha256(data).hexdigest()+'";',
           "struct Range { std::uint8_t clip; std::int16_t first,last; std::int32_t start,end; std::uint32_t end_bits; };",
           "inline constexpr std::array<Range,6> ranges{{"]
    for row in record["tables"]["clips"]:
        bits=struct.unpack("<I",struct.pack("<f",row["end_float_ms"]))[0]
        lines.append("    {%d,%d,%d,%d,%d,0x%08xU}," % (row["clip"],row["start_frame"],row["end_frame"],row["start_ms"],row["end_clamped_ms"],bits))
    lines.extend(["}};",
        "struct Case { const char* name; bool start; std::uint8_t clip; std::int32_t before,delta; bool restart; std::int32_t after,requested; bool completed; };",
        "inline constexpr std::array<Case,54> cases{{"])
    for row in cases:
        calls=row["virtual_24_calls_ms"]
        if len(calls)!=1:raise ValueError("expected exactly one recorded animate request")
        value=[json.dumps(row["name"]),str(row["kind"]=="start").lower(),str(row["clip"]),
               str(row["clock_before"]),str(row.get("delta_ms",0)),str(row.get("restart",False)).lower(),
               str(row["clock_after"]),str(calls[0]),str(bool(row.get("completion_return",0))).lower()]
        lines.append("    {"+",".join(value)+"},")
    lines.extend(["}};","} // namespace g1_timeline_fixture",""])
    return "\n".join(lines)


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--fixture",type=Path,required=True)
    parser.add_argument("--output",type=Path,required=True)
    parser.add_argument("--check",action="store_true")
    args=parser.parse_args();text=generate(args.fixture)
    if args.check:
        if args.output.read_text()!=text:raise ValueError("generated fixture header differs")
    else:args.output.write_text(text)
    print(json.dumps({"cases":54,"output":str(args.output),"check":args.check}))


if __name__=="__main__":main()
